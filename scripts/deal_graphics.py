#!/usr/bin/env python3
"""Deterministic BestDealHunter branded deal cards (free: Pillow + the bundled Inter fonts, SIL OFL).

Design: the bold style of Alpha's deal images, chosen by the owner (2026-10-14): navy spotlight
background, BestDealHunter wordmark, the store name on a yellow corner tag, a red brush "% OFF" with a
yellow "SAVE" strip, big yellow price, struck-through reference price, "SEE DEAL" button, and a footer
with the website, the price-check time and "Prices may change". Check rows show only what the deal
record says (seller, stock, price-check time); no product features are invented.

Policy (issue #1, agreed with Alpha):
* Every number on a card (price, reference price, % off, price-check time) is computed from the
  validated deal record. Nothing is typed by hand or generated by AI. The % is rounded down.
* A product picture appears only when the deal names one in `image_source` (images/source/...):
  an authorized photo, or an AI picture from ai_product_art.py (`image_source_kind:
  "ai_illustration"`), which is labelled "ILLUSTRATION" because it shows the kind of product, not
  the exact item. Without one the card is typographic. Store photography is never used.
* Retailer names are plain text, never logos.

Sizes: 1080x1350 (Instagram 4:5 feed, "feed") and 1080x1080 ("square", the website).

Usage:
  python scripts/deal_graphics.py --preview   # render every deals.json card into docs/graphics-previews/ for review
"""
import argparse
import hashlib
import json
import random
import re
import sys
from datetime import date, datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from PIL import Image, ImageChops, ImageDraw, ImageFilter, ImageFont, ImageOps

from links import disclosure, is_affiliate_link

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "assets" / "fonts"
WEIGHTS = {800: "Inter-ExtraBold.otf", 700: "Inter-Bold.otf", 500: "Inter-Medium.otf", 400: "Inter-Regular.otf"}
FONT = FONTS / WEIGHTS[800]
SOURCE = ROOT / "images" / "source"
PREVIEWS = ROOT / "docs" / "graphics-previews"
SIZES = {"feed": (1080, 1350), "square": (1080, 1080)}
SITE = "bestdealhunters.com"
PACIFIC = ZoneInfo("America/Los_Angeles")

# Alpha's bold deal-image palette.
BACKGROUND, GLOW, GLOW_2, WHITE, GRAY, MUTED = "#07101F", "#1450C8", "#0E2A66", "#FFFFFF", "#B6C2D6", "#8A94A6"
YELLOW, RED, RED_DARK, PANEL, PANEL_EDGE = "#FACC15", "#E11D2E", "#7F0A14", "#050B16", "#3A4A66"
AI_KIND = "ai_illustration"  # earlier ai_product_art.py pictures: studio shot inside the card
LISTING_PHOTO = "listing_photo"  # the retailer listing's own product photo (eBay Browse API), shown unedited
AI_SCENE = "ai_scene"  # AI lifestyle photo from the product name only (fills the card)
AI_SCENE_FROM_PHOTO = "ai_scene_from_photo"  # lifestyle scene made by AI from the real listing photo
REFERENCE_LABELS = {"Best Buy": "Comparable value", "Amazon": "List price", "Macy's": "Original price"}
_fonts = {}


class CardError(ValueError):
    pass


def font(size, weight=700):
    key = (int(size), weight)
    if key not in _fonts:
        _fonts[key] = ImageFont.truetype(str(FONTS / WEIGHTS[weight]), int(size))
    return _fonts[key]


def money(value):
    value = float(value)
    return f"${value:,.0f}" if value == int(value) else f"${value:,.2f}"


def price_checked(deal):
    """When the price was checked (aware datetime), from price_checked_at or auto_published_at; else None."""
    for field in ("price_checked_at", "auto_published_at"):
        raw = deal.get(field)
        if raw:
            try:
                stamp = datetime.fromisoformat(str(raw).replace("Z", "+00:00"))
            except ValueError:
                raise CardError(f"{field} must be an ISO 8601 time") from None
            if stamp.tzinfo is None:
                raise CardError(f"{field} needs a time zone")
            return stamp
    return None


def as_of_text(deal):
    """'Oct 13, 2026, 10:30 PM PT' from the price-check time; the verification day when only that is known."""
    stamp = price_checked(deal)
    if stamp:
        t = stamp.astimezone(PACIFIC)
        return f"{t:%b} {t.day}, {t.year}, {t.hour % 12 or 12}:{t:%M} {t:%p} PT"
    verified = deal.get("verified_date")
    try:
        day = date.fromisoformat(verified) if verified else None
    except ValueError:
        raise CardError("verified_date must be YYYY-MM-DD") from None
    return f"{day:%b} {day.day}, {day.year}" if day else None


def card_facts(deal):
    """Everything printed on a card, derived only from the deal record."""
    try:
        price, original = float(deal["price"]), float(deal["original_price"])
        title, store = str(deal["title"]).strip(), str(deal["store"]).strip()
    except (KeyError, TypeError, ValueError) as exc:
        raise CardError(f"deal is missing card data: {exc}") from None
    if not (0 < price < original) or not title or not store:
        raise CardError("deal needs a title, store and 0 < price < original_price")
    verified = deal.get("verified_date")
    try:
        day = date.fromisoformat(verified) if verified else None
        verified_text = f"{day:%b} {day.day}, {day.year}" if day else None
    except ValueError:
        raise CardError("verified_date must be YYYY-MM-DD") from None
    return {
        "title": title,
        "store": store,
        "price": money(price),
        "reference": money(original),
        "reference_label": deal.get("reference_price_label") or REFERENCE_LABELS.get(store, "Was"),
        "percent": int((original - price) * 100 // original),  # floor: never overstate the discount
        "savings": money(round(original - price, 2)),
        "verified": verified_text,
        "as_of": as_of_text(deal),
        "category": str(deal.get("category") or "").upper(),
    }


def authorized_photo(deal):
    raw = deal.get("image_source")
    if raw is None:
        return None
    if not isinstance(raw, str) or not re.fullmatch(r"images/source/[\w.-]+\.(?:png|jpe?g|webp)", raw, re.I):
        raise CardError("image_source must be an authorized photo under images/source/")
    path = (ROOT / raw).resolve()
    if not path.is_relative_to(SOURCE.resolve()) or not path.is_file():
        raise CardError(f"image_source not found: {raw}")
    return path


# ---------------------------------------------------------------- drawing helpers

def text_width(draw, text, face):
    return draw.textlength(text, font=face)


def wrap(draw, text, face, max_width, max_lines):
    words, lines, current = text.split(), [], ""
    for word in words:
        candidate = f"{current} {word}".strip()
        if text_width(draw, candidate, face) <= max_width:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    if len(lines) > max_lines:
        lines = lines[:max_lines]
        while lines[-1] and text_width(draw, lines[-1] + "…", face) > max_width:
            lines[-1] = lines[-1][:-1].rstrip()
        lines[-1] += "…"
    return lines


def fit(draw, text, weight, start, max_width, minimum=24):
    size = start
    while size > minimum and text_width(draw, text, font(size, weight)) > max_width:
        size -= 2
    return font(size, weight)


def ink_height(face):
    """Height of capital letters and digits, for vertical centring."""
    box = face.getbbox("0H")
    return box[3] - box[1]


def background(size):
    """Deep navy with a blue spotlight, as in Alpha's deal images."""
    w, h = size
    base = Image.new("RGB", size, BACKGROUND)
    for box, colour, strength, blur in (((w * 0.25, h * 0.12, w * 1.25, h * 0.75), GLOW, 150, 160),
                                        ((-w * 0.4, h * 0.55, w * 0.5, h * 1.2), GLOW_2, 90, 140)):
        mask = Image.new("L", size, 0)
        ImageDraw.Draw(mask).ellipse(box, fill=strength)
        base = Image.composite(Image.new("RGB", size, colour), base, mask.filter(ImageFilter.GaussianBlur(blur)))
    return base.convert("RGBA")


def cart_icon(draw, x, y, s, colour):
    draw.line((x, y, x + s * 0.18, y), fill=colour, width=int(s * 0.08))
    draw.polygon([(x + s * 0.16, y + s * 0.12), (x + s, y + s * 0.12), (x + s * 0.88, y + s * 0.58),
                  (x + s * 0.28, y + s * 0.58)], outline=colour, width=int(s * 0.08))
    for cx in (x + s * 0.36, x + s * 0.8):
        draw.ellipse((cx - s * 0.09, y + s * 0.72, cx + s * 0.09, y + s * 0.9), fill=colour)


def brush(size, colour, seed):
    """A red paint-brush stroke with ragged edges; deterministic for a given seed."""
    w, h = size
    rnd = random.Random(seed)
    img = Image.new("RGBA", size, (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    top = [(w * 0.04 + w * 0.92 * i / 40, h * 0.12 + rnd.uniform(-h * 0.08, h * 0.06)) for i in range(41)]
    bottom = [(w * 0.96 - w * 0.92 * i / 40, h * 0.88 + rnd.uniform(-h * 0.06, h * 0.08)) for i in range(41)]
    draw.polygon(top + [(w * 0.98, h * 0.5)] + bottom + [(0, h * 0.5)], fill=colour)
    for _ in range(14):  # dry-brush streaks at both ends
        y, length = rnd.uniform(h * 0.15, h * 0.85), rnd.uniform(w * 0.03, w * 0.1)
        x = w * 0.02 if rnd.random() < 0.5 else w * 0.95 - length
        draw.rectangle((x, y, x + length, y + rnd.uniform(3, 9)), fill=colour)
    return img


def slanted(text, face, fill, stroke=0, stroke_fill=None, shear=0.18):
    """Text sheared to look italic (the bundled Inter has no italic)."""
    box = ImageDraw.Draw(Image.new("RGBA", (1, 1))).textbbox((0, 0), text, font=face, stroke_width=stroke)
    w, h = box[2] - box[0] + 20, box[3] - box[1] + 20
    img = Image.new("RGBA", (w + int(h * shear), h), (0, 0, 0, 0))
    ImageDraw.Draw(img).text((10 - box[0] + int(h * shear), 10 - box[1]), text, font=face, fill=fill,
                             stroke_width=stroke, stroke_fill=stroke_fill)
    return img.transform(img.size, Image.AFFINE, (1, shear, 0, 0, 1, 0), Image.BICUBIC)


def fact_rows(deal, facts):
    """Check rows built only from what the deal record says."""
    rows = []
    seller = str(deal.get("seller") or "").strip()
    if seller and seller.lower() != "unverified":
        rows.append((f"Sold by {seller}", "Checked on the store's own page"))
    if "stock" in str(deal.get("availability") or "").lower():
        rows.append(("In stock online", "At the time of the price check"))
    if facts["as_of"]:
        rows.append(("Price checked", facts["as_of"]))
    return rows


def trim(art, threshold=40, pad=0.08):
    """Cut away a plain background border (as AI pictures have) so the product fills the space."""
    corner = Image.new("RGB", art.size, art.getpixel((2, 2)))
    diff = ImageChops.difference(art, corner).convert("L").point(lambda v: 255 if v > threshold else 0)
    box = diff.getbbox()
    if not box:
        return art
    px, py = int((box[2] - box[0]) * pad), int((box[3] - box[1]) * pad)
    return art.crop((max(0, box[0] - px), max(0, box[1] - py), min(art.width, box[2] + px), min(art.height, box[3] + py)))


def draw_listing_photo(canvas, path, box, credit, stage_bottom):
    """The real product photo, large on a bright full-width stage matched to the photo's own background, with a
    soft floor shadow. The photo is only resized and cropped of empty margins; the product is never edited.
    Its source is credited."""
    w = canvas.width
    x0, y0, x1, y1 = (int(v) for v in box)
    with Image.open(path) as src:
        photo = trim(ImageOps.exif_transpose(src).convert("RGB"), threshold=18, pad=0.08)
    edge = photo.getpixel((1, 1))
    stage_top, stage_bottom = y0 - 8, int(stage_bottom)
    stage = Image.new("RGB", (w, stage_bottom - stage_top), edge)
    darker = tuple(int(c * 0.86) for c in edge)
    stage = Image.composite(Image.new("RGB", stage.size, darker), stage, Image.linear_gradient("L").resize(stage.size))
    canvas.paste(stage, (0, stage_top))
    photo = ImageOps.contain(photo, (int((x1 - x0) * 0.92), y1 - y0 - 60), Image.Resampling.LANCZOS)
    left, top = (w - photo.width) // 2, y0 + 24 + (y1 - y0 - 60 - photo.height) // 2
    shadow = Image.new("L", canvas.size, 0)
    ImageDraw.Draw(shadow).ellipse((left + photo.width * 0.15, top + photo.height * 0.93,
                                    left + photo.width * 0.85, top + photo.height * 0.93 + 40), fill=90)
    canvas.paste(Image.new("RGB", canvas.size, "#4A5468"), (0, 0), shadow.filter(ImageFilter.GaussianBlur(20)))
    fade = Image.new("L", photo.size, 0)
    inset = max(6, min(photo.size) // 30)  # inside the 8% empty margin, so only background is softened
    ImageDraw.Draw(fade).rectangle((inset, inset, photo.width - inset, photo.height - inset), fill=255)
    canvas.paste(photo, (left, top), fade.filter(ImageFilter.GaussianBlur(inset * 0.7)))
    draw = ImageDraw.Draw(canvas)
    draw.text((w - 48, stage_top + 34), credit, font=font(20, 700), fill="#6B7487", anchor="rs")


def draw_art(canvas, path, box, illustration):
    """The product picture, scaled to fit the box (never cropped), its edges faded into the background.
    AI pictures carry an "Illustration" label: they show the kind of product, not the exact item."""
    x0, y0, x1, y1 = (int(v) for v in box)
    with Image.open(path) as src:
        art = ImageOps.exif_transpose(src).convert("RGB")
    art = trim(art)
    art = ImageOps.contain(art, (x1 - x0, y1 - y0), Image.Resampling.LANCZOS)
    mask = Image.new("L", art.size, 0)
    inset = max(8, min(art.size) // 14)
    ImageDraw.Draw(mask).rounded_rectangle((inset, inset, art.width - inset, art.height - inset), radius=inset * 2,
                                           fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(inset * 0.8))
    left, top = x0 + (x1 - x0 - art.width) // 2, y0 + (y1 - y0 - art.height) // 2
    canvas.paste(art, (left, top), mask)
    if illustration:
        draw = ImageDraw.Draw(canvas)
        face = font(22, 700)
        label = "ILLUSTRATION"
        right, top_y = left + art.width - inset, top + inset
        draw.rounded_rectangle((right - text_width(draw, label, face) - 28, top_y, right, top_y + 38), radius=19,
                               fill=PANEL)
        draw.text((right - 14, top_y + 19), label, font=face, fill=GRAY, anchor="rm")


def scene_background(path, size, vertical=0.75):
    """A lifestyle photo filling the card, darkened at the top (header, title) and bottom (badge, prices)."""
    w, h = size
    with Image.open(path) as src:
        photo = ImageOps.fit(ImageOps.exif_transpose(src).convert("RGB"), size, Image.Resampling.LANCZOS,
                             centering=(0.5, vertical))
    shade = Image.new("L", size, 0)
    draw = ImageDraw.Draw(shade)
    for y in range(h):
        top = 215 * max(0.0, 1 - y / (h * 0.30)) ** 1.2
        bottom = 238 * max(0.0, (y - h * 0.52) / (h * 0.48)) ** 0.9
        draw.line((0, y, w, y), fill=int(min(240, top + bottom)))
    return Image.composite(Image.new("RGB", size, BACKGROUND), photo, shade).convert("RGBA")


def scene_band(path, size, band_bottom):
    """A scene from a real product photo, fitted into the visible band above the price area (so the product is
    never hidden behind the badge or prices), darkened behind the header and faded into navy at its lower edge."""
    w, h = size
    band = int(band_bottom)
    with Image.open(path) as src:
        photo = ImageOps.fit(ImageOps.exif_transpose(src).convert("RGB"), (w, band), Image.Resampling.LANCZOS,
                             centering=(0.5, 0.45))
    canvas = background(size)
    shade = Image.new("L", (w, band), 0)
    draw = ImageDraw.Draw(shade)
    for y in range(band):
        top = 215 * max(0.0, 1 - y / (h * 0.30)) ** 1.2
        bottom = 255 * max(0.0, (y - (band - 230)) / 230) ** 1.3
        draw.line((0, y, w, y), fill=int(min(255, top + bottom)))
    canvas.paste(photo, (0, 0), Image.eval(shade, lambda v: 255 - v))
    return canvas


def render_card(deal, kind="feed"):
    """Alpha's bold deal-image style, drawn from the deal record only (owner's choice, 2026-10-14)."""
    facts = card_facts(deal)
    photo_path = authorized_photo(deal)
    w, h = SIZES[kind]
    k = 1.0 if kind == "feed" else 0.84
    scene = bool(photo_path) and deal.get("image_source_kind") in (AI_SCENE, AI_SCENE_FROM_PHOTO)
    listing = bool(photo_path) and deal.get("image_source_kind") == LISTING_PHOTO
    b = 0.78 if scene or listing else 1.0  # smaller badge, so the product photo stays visible
    if deal.get("image_source_kind") == AI_SCENE_FROM_PHOTO and photo_path:
        top_of_badge = h - 40 * k - (36 * k if is_affiliate_link(deal.get("url")) else 0) - 260 * k - 340 * k * b
        canvas = scene_band(photo_path, (w, h), top_of_badge + 110 * k)
    elif scene:
        canvas = scene_background(photo_path, (w, h))
    else:
        canvas = background((w, h))
    draw = ImageDraw.Draw(canvas)
    margin = 48

    # Header: cart icon, wordmark, tagline; the store name as plain text on a yellow corner tag (no logo).
    cart_icon(draw, margin, 40, 80 * k, YELLOW)
    x = margin + 100 * k
    mark_face = font(66 * k, 800)
    for word, colour in (("Best", WHITE), ("Deal", YELLOW), ("Hunter", WHITE)):
        draw.text((x, 34), word, font=mark_face, fill=colour)
        x += text_width(draw, word, mark_face)
    draw.line((margin + 100 * k, 34 + 82 * k, x, 34 + 82 * k), fill=YELLOW, width=4)
    draw.text((margin + 100 * k, 34 + 96 * k), "VERIFIED 50%+ DEALS  •  PRICE CHECKED", font=font(22 * k, 700),
              fill=GRAY)
    store = facts["store"].upper()
    store_face = fit(draw, store, 800, int(46 * k), w - x - 140)
    tag_w = text_width(draw, store, store_face)
    draw.polygon([(w - tag_w - 110, 0), (w, 0), (w, 150 * k), (w - tag_w - 60, 150 * k)], fill=YELLOW)
    draw.text((w - 36, 75 * k), store, font=store_face, fill=BACKGROUND, anchor="rm")

    # With a picture (an AI illustration or an authorized photo), it fills the middle under a shorter title,
    # drawn first so the % OFF badge overlaps its lower edge as in Alpha's images.
    foot_y = h - 40 * k - (36 * k if is_affiliate_link(deal.get("url")) else 0)
    badge_top = foot_y - 260 * k - 340 * k * b
    if photo_path and not scene:
        title_face = font(60 * k, 800)
        lines = wrap(draw, facts["title"], title_face, w - 2 * margin, 2)
        art_box = (margin, 190 * k + len(lines) * title_face.size * 1.12 + 12 * k, w - margin,
                   badge_top + (60 if listing else 120) * k)
        if deal.get("image_source_kind") == LISTING_PHOTO:
            draw_listing_photo(canvas, photo_path, art_box, f"PHOTO: {facts['store'].upper()} LISTING",
                               stage_bottom=badge_top + 200 * k * b)
        else:
            draw_art(canvas, photo_path, art_box, illustration=deal.get("image_source_kind") == AI_KIND)
        draw = ImageDraw.Draw(canvas)

    # Bottom up: footer, price panel + button, then the brush badge; the title and rows fill the top.
    foot = f"{SITE}  ·  Price as of {facts['as_of']}  ·  Prices may change" if facts["as_of"] else \
        f"{SITE}  ·  Prices may change"
    y = h - 40 * k
    if is_affiliate_link(deal.get("url")):
        draw.text((w / 2, y), disclosure(deal)[0], font=font(24 * k, 500), fill=GRAY, anchor="ms")
        y -= 36 * k
    draw.text((w / 2, y), foot, font=fit(draw, foot, 500, int(25 * k), w - 2 * margin), fill=GRAY, anchor="ms")

    panel = (margin, y - 260 * k, w * 0.66, y - 70 * k)
    draw.rounded_rectangle(panel, radius=26, fill=PANEL, outline=PANEL_EDGE, width=3)
    mid = margin + (panel[2] - margin) * 0.42
    draw.line((mid, panel[1] + 30 * k, mid, panel[3] - 30 * k), fill=PANEL_EDGE, width=3)
    ref_face = fit(draw, facts["reference"], 800, int(54 * k), mid - margin - 50)
    draw.text((margin + 30, panel[1] + 95 * k), facts["reference"], font=ref_face, fill=MUTED, anchor="ls")
    ref_w = text_width(draw, facts["reference"], ref_face)
    draw.line((margin + 26, panel[1] + 80 * k, margin + 34 + ref_w, panel[1] + 62 * k), fill=RED, width=6)
    draw.text((margin + 30, panel[1] + 145 * k), facts["reference_label"],
              font=fit(draw, facts["reference_label"], 700, int(28 * k), mid - margin - 50), fill=GRAY, anchor="ls")
    dollars, _, cents = facts["price"].partition(".")
    cents_face = font(56 * k, 800)
    room = panel[2] - mid - 40 - (text_width(draw, "." + cents, cents_face) if cents else 0)
    price_face = fit(draw, dollars, 800, int(130 * k), room)
    total = text_width(draw, dollars, price_face) + (text_width(draw, "." + cents, cents_face) if cents else 0)
    px = (mid + panel[2]) / 2 - total / 2
    base = panel[1] + 120 * k
    draw.text((px, base), dollars, font=price_face, fill=YELLOW, anchor="ls")
    if cents:
        draw.text((px + text_width(draw, dollars, price_face) + 2, base - ink_height(price_face) * 0.42), "." + cents,
                  font=cents_face, fill=YELLOW, anchor="ls")
    draw.text(((mid + panel[2]) / 2, panel[1] + 176 * k), "Sale Price", font=font(28 * k, 700), fill=WHITE,
              anchor="ms")
    button = (w * 0.66 + 24, panel[1] + 20 * k, w - margin, panel[3] - 20 * k)
    draw.rounded_rectangle(button, radius=24, fill=YELLOW)
    centre = ((button[0] + button[2]) / 2, (button[1] + button[3]) / 2)
    draw.text((centre[0], centre[1] - 22 * k), "SEE DEAL", font=font(40 * k, 800), fill=BACKGROUND, anchor="mm")
    draw.text((centre[0], centre[1] + 24 * k), "LINK IN BIO ›", font=font(28 * k, 800), fill=BACKGROUND, anchor="mm")

    stroke = brush((int(700 * k * b), int(220 * k * b)), RED, facts["percent"]).rotate(4, expand=True,
                                                                               resample=Image.BICUBIC)
    canvas.alpha_composite(stroke, (int(margin - 20), int(badge_top)))
    pct = slanted(f"{facts['percent']}% OFF", font(128 * k * b, 800), WHITE, stroke=3, stroke_fill=RED_DARK)
    pct = pct.rotate(4, expand=True, resample=Image.BICUBIC)
    canvas.alpha_composite(pct, (int(margin - 20 + (stroke.width - pct.width) / 2),
                                 int(badge_top + (stroke.height - pct.height) / 2 - 6 * k)))
    strip = Image.new("RGBA", (int(380 * k * b), int(78 * k * b)), YELLOW)
    save_text = f"SAVE {facts['savings']}"
    ImageDraw.Draw(strip).text((strip.width / 2, strip.height / 2), save_text,
                               font=fit(draw, save_text, 800, int(46 * k * b), strip.width - 30), fill=BACKGROUND,
                               anchor="mm")
    strip = strip.rotate(4, expand=True, resample=Image.BICUBIC)
    canvas.alpha_composite(strip, (int(margin + 300 * k * b), int(badge_top + stroke.height - 40 * k * b)))
    draw = ImageDraw.Draw(canvas)

    # Title, then (without a picture) check rows, above the badge.
    if scene:
        title_face = font(58 * k, 800)
        for i, line in enumerate(wrap(draw, facts["title"], title_face, w - 2 * margin, 2)):
            draw.text((margin, 190 * k + i * title_face.size * 1.12), line, font=title_face, fill=WHITE,
                      stroke_width=2, stroke_fill=BACKGROUND)
        face = font(20 * k, 700)
        label = ("AI SCENE FROM LISTING PHOTO" if deal.get("image_source_kind") == AI_SCENE_FROM_PHOTO
                 else "AI ILLUSTRATION")
        top = 190 * k + 2 * title_face.size * 1.12 + 14 * k
        draw.rounded_rectangle((margin, top, margin + text_width(draw, label, face) + 28, top + 34 * k), radius=17,
                               fill=PANEL)
        draw.text((margin + 14, top + 17 * k), label, font=face, fill=GRAY, anchor="lm")
        return canvas.convert("RGB")
    if photo_path:
        for i, line in enumerate(lines):
            draw.text((margin, 190 * k + i * title_face.size * 1.12), line, font=title_face, fill=WHITE)
        return canvas.convert("RGB")
    y = 200 * k
    limit = badge_top - 20 * k
    text_w = w - 2 * margin
    title_face = font(70 * k, 800)
    lines = wrap(draw, facts["title"], title_face, text_w, 3 if kind == "feed" else 2)
    for line in lines:
        draw.text((margin, y), line, font=title_face, fill=WHITE)
        y += title_face.size * 1.12
    y += 26 * k
    for main, detail in fact_rows(deal, facts):
        if y + 70 * k > limit:
            break
        draw.rounded_rectangle((margin, y, margin + 64 * k, y + 64 * k), radius=14, outline=YELLOW, width=4)
        draw.text((margin + 32 * k, y + 33 * k), "✓", font=font(40 * k, 800), fill=YELLOW, anchor="mm")
